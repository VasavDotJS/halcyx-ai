/**
 * Maps `items` through `fn` with at most `limit` calls in flight, preserving order.
 * Used on hot paths (encrypt/decrypt per file, blob uploads) to avoid both fully sequential
 * work and unbounded fan-out (memory spikes, GitHub secondary rate limits).
 */
export async function mapLimit<T, R>(items: readonly T[], limit: number, fn: (item: T, index: number) => Promise<R>): Promise<R[]> {
  const out = new Array<R>(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next;
      next += 1;
      out[i] = await fn(items[i]!, i);
    }
  };
  await Promise.all(Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, worker));
  return out;
}
