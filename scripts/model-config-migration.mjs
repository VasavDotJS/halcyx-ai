// Generates a Supabase migration that publishes config/models.json as the newest remote model
// config, so the bundled list and the seeded list can't drift (tests/modelConfigSeed.test.ts).
//   node scripts/model-config-migration.mjs        → backend/supabase/migrations/<timestamp>_model_config_<version>.sql
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const config = JSON.parse(readFileSync(join(root, 'config/models.json'), 'utf8'));
if (!/^\d{4}-\d{2}-\d{2}$/.test(config.version)) throw new Error('config/models.json version must be YYYY-MM-DD');
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const json = JSON.stringify(config).replace(/'/g, "''");
const sql = `-- Generated by scripts/model-config-migration.mjs from config/models.json. Do not edit by hand.
insert into public.model_config (version, config)
values ('${config.version}', '${json}'::jsonb)
on conflict (version) do nothing;
`;
const file = join(root, 'backend/supabase/migrations', `${stamp}_model_config_${config.version.replace(/-/g, '')}.sql`);
writeFileSync(file, sql);
console.warn(`Wrote ${file}`);
